/**
 * What each demo charity needs. Products come from Channel3 (searched once, saved in products.cache.json),
 * except Harbor's food items: Channel3 has no grocery catalog (NOTES.md §13), so those are hand-entered.
 *
 * `match` / `avoid` are case-insensitive regexes tested against the product title, so a search result that is
 * the wrong thing (cat food for "tuna") is never picked. The first matching in-stock result wins.
 */
import type { Category } from "@needgrid/shared";

export interface ManualProduct {
  title: string;
  unitPriceCents: number;
  retailer: string;
  /** A real retailer search page, so the link works. */
  url: string;
  packSize: number | null;
}

export interface NeedTemplate {
  key: string;
  title: string;
  description: string;
  category: Category;
  /** Purchasable unit, e.g. "pack", "bag", "coat". */
  unit: string;
  urgency?: 1 | 2 | 3;
  /** Fixed number of units. Otherwise the seed picks one that gives a realistic target. */
  quantity?: number;
  query?: string;
  match?: string[];
  avoid?: string[];
  /** Highest acceptable price for one unit, in cents (default DEFAULT_MAX_UNIT_CENTS). Skips designer/industrial listings. */
  maxUnitCents?: number;
  manual?: ManualProduct;
}

